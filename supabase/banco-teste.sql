-- 1) PEÇAS (mesmas colunas do banco do grupo)
create table if not exists public.pecas (
  id                bigint generated by default as identity primary key,
  sku               text,
  nome              text not null,
  categoria         text,
  quantidade_atual  integer not null default 0,
  estoque_minimo    integer not null default 0,
  preco_venda       numeric(12,2) not null default 0,
  ean               text,
  localizacao       text,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz default now()
);

-- 2) MOVIMENTAÇÕES (entradas e saídas)
create table if not exists public.movimentacoes (
  id              bigint generated by default as identity primary key,
  peca_id         bigint not null references public.pecas(id) on delete cascade,
  tipo_movimento  text not null check (tipo_movimento in ('entrada', 'saida')),
  quantidade      integer not null check (quantidade > 0),
  data_hora       timestamptz not null default now(),
  documento       text,
  motivo          text,
  usuario_id      uuid
);

-- 3) ORÇAMENTOS (o mesmo SQL do arquivo orcamentos.sql)
create table if not exists public.orcamentos (
  id          bigint generated by default as identity primary key,
  cliente     text not null,
  desconto    numeric(5,2) not null default 0 check (desconto >= 0 and desconto <= 100),
  status      text not null default 'aberto' check (status in ('aberto', 'aprovado', 'cancelado')),
  validade    date not null default (current_date + 7),
  observacao  text,
  created_at  timestamptz not null default now()
);

create table if not exists public.orcamento_itens (
  id              bigint generated by default as identity primary key,
  orcamento_id    bigint not null references public.orcamentos(id) on delete cascade,
  peca_id         bigint not null references public.pecas(id),
  quantidade      integer not null check (quantidade > 0),
  preco_unitario  numeric(12,2) not null default 0 check (preco_unitario >= 0)
);
create index if not exists orcamento_itens_orcamento_idx on public.orcamento_itens (orcamento_id);

-- 4) PERMISSÕES: o app usa a chave pública (anon), igual ao banco do grupo
alter table public.pecas            enable row level security;
alter table public.movimentacoes    enable row level security;
alter table public.orcamentos       enable row level security;
alter table public.orcamento_itens  enable row level security;

drop policy if exists "teste acesso app" on public.pecas;
create policy "teste acesso app" on public.pecas for all to anon, authenticated using (true) with check (true);
drop policy if exists "teste acesso app" on public.movimentacoes;
create policy "teste acesso app" on public.movimentacoes for all to anon, authenticated using (true) with check (true);
drop policy if exists "orcamentos acesso app" on public.orcamentos;
create policy "orcamentos acesso app" on public.orcamentos for all to anon, authenticated using (true) with check (true);
drop policy if exists "orcamento_itens acesso app" on public.orcamento_itens;
create policy "orcamento_itens acesso app" on public.orcamento_itens for all to anon, authenticated using (true) with check (true);

