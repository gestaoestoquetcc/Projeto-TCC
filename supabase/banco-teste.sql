-- 6) MOVIMENTAÇÕES DE EXEMPLO: saídas nos últimos 90 dias (para a Previsão IA ter dados)
--    Só entra se ainda não houver movimentações.
insert into public.movimentacoes (peca_id, tipo_movimento, quantidade, data_hora, documento, motivo)
select p.id,
       'saida',
       1 + floor(random() * 3)::int,
       now() - (d || ' days')::interval - (floor(random() * 10) || ' hours')::interval,
       'OS-' || (4000 + d),
       'Balcão'
from public.pecas p
cross join generate_series(0, 89) as d
where p.sku in ('PST-2041', 'DSC-1090', 'FLT-5011')
  and random() < case p.sku when 'FLT-5011' then 0.55 when 'PST-2041' then 0.40 else 0.25 end
  and not exists (select 1 from public.movimentacoes);

-- algumas entradas de fornecedor
insert into public.movimentacoes (peca_id, tipo_movimento, quantidade, data_hora, documento, motivo)
select p.id, 'entrada', 20, now() - (d || ' days')::interval, 'NF-e ' || (12000 + d), 'Fornecedor'
from public.pecas p
cross join (values (75), (45), (15)) as dias(d)
where p.sku in ('PST-2041', 'FLT-5011')
  and (select count(*) from public.movimentacoes where tipo_movimento = 'entrada') = 0;

